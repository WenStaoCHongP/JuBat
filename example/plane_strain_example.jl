### 注意事项：

1. 泊松比限制
   - 平面应力：ν 可以接近 0.5
   - 平面应变：ν < 0.45（否则数值不稳定）

2. 应力量级
   - 平面应变的应力通常是平面应力的 1.5-2.5 倍
   - 需要检查是否超过材料屈服强度

3. Von Mises 应力
   - 平面应力：不包含 σ_zz
   - 平面应变：包含 σ_zz（约束应力）

4. 物理解释
   - 平面应力：允许厚度方向变化，应力较小
   - 平面应变：厚度方向受约束，应力较大
