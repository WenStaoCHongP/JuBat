# ========================================================================
# 6. 理论计算对比
# ========================================================================

println("\n" * "="^70)
println("理论对比：相同初始应变下的应力")
println("="^70)

# 材料参数
E = 100e9  # 100 GPa
ν = 0.3
α = 1.5e-5  # K^-1
β_c = 0.03
c_s_max = 33133  # mol/m³

# 初始应变
ΔT_K = 10.0  # K
ΔSOC = 0.3
ε_0 = α * ΔT_K + β_c * c_s_max * ΔSOC

println("\n初始应变:")
println("  ε_thermal = α × ΔT = $(α * ΔT_K)")
println("  ε_diffusion = β_c × ΔSOC = $(β_c * ΔSOC)")
println("  ε_0 总计 = $(ε_0)")

# 平面应力下的应力
σ_stress = E / (1 - ν^2) * (1 + ν) * ε_0
println("\n平面应力:")
println("  弹性模量因子 = E/(1-ν²) = $(E/(1-ν^2)/1e9) GPa")
println("  初始应力系数 = (1+ν) = $(1+ν)")
println("  σ = $(σ_stress/1e6) MPa")

# 平面应变下的应力
σ_strain = E / ((1 + ν) * (1 - 2*ν)) * (1 + 2*ν) * ε_0
println("\n平面应变:")
println("  弹性模量因子 = E/((1+ν)(1-2ν)) = $(E/((1+ν)*(1-2*ν))/1e9) GPa")
println("  初始应力系数 = (1+2ν) = $(1+2*ν)")
println("  σ = $(σ_strain/1e6) MPa")

# 对比
ratio = σ_strain / σ_stress
println("\n应力比值:")
println("  σ_strain / σ_stress = $(ratio)")
println("  差异: $((ratio-1)*100)%")

println("\n结论:")
println("  平面应变的应力约为平面应力的 $(round(ratio, digits=2)) 倍")
println("  原因：垂直方向受约束，材料无法自由膨胀")

